#!/usr/bin/env bash
# Schema snapshot of a release (the "schema gate").
#
#   ci/schema-snapshot.sh [--through NNNN] <out.sql>
#
# Creates a scratch database on the server behind CRAWLX_TEST_DATABASE_URL, applies the
# migrations 0001..NNNN of crates/crawlx-storage/migrations/ (all of them without --through)
# exactly as sqlx does (one transaction per file, `_sqlx_migrations` row with the SHA-384
# checksum sqlx::migrate! computes), dumps the schema with pg_dump and writes a
# schema-relative, deterministic SQL file:
#
#   * `pg_dump --schema-only --no-owner --no-privileges --no-comments` of the scratch
#     database with the `public.` qualifier and the session SETs removed, so the file loads
#     into whatever `search_path` is current (production `public`, the per-test schema of
#     the integration tests);
#   * one `INSERT INTO _sqlx_migrations` per applied migration (no timestamps), so the
#     embedded migrator skips what the snapshot already contains and validates its checksums.
#
# `crates/crawlx-storage/schema/vNNNN.sql` is the committed snapshot of the previous
# release; `migrations_apply_on_top_of_the_previous_release_snapshot` (tests/pg_faults.rs)
# loads it and runs the embedded migrator on top. Regenerate with the same major pg_dump
# version as the CI postgres service (ci.yml `schema-snapshot`), then `git diff`.
#
# Requires: psql, pg_dump (>= server major), sha384sum, CRAWLX_TEST_DATABASE_URL (a role
# with CREATEDB).
set -euo pipefail
cd "$(dirname "$0")/.."

through=""
out=""
while [ $# -gt 0 ]; do
    case "$1" in
        --through)
            [ $# -ge 2 ] || { echo "--through needs a value" >&2; exit 2; }
            through="$2"
            shift 2
            ;;
        -h | --help)
            sed -n '2,24p' "$0"
            exit 0
            ;;
        *)
            if [ -n "$out" ]; then echo "unexpected argument: $1" >&2; exit 2; fi
            out="$1"
            shift
            ;;
    esac
done
[ -n "$out" ] || { echo "usage: ci/schema-snapshot.sh [--through NNNN] <out.sql>" >&2; exit 2; }
if [ -n "$through" ] && ! [[ "$through" =~ ^[0-9]+$ ]]; then
    echo "--through must be a migration number (e.g. 0008)" >&2
    exit 2
fi
: "${CRAWLX_TEST_DATABASE_URL:?set CRAWLX_TEST_DATABASE_URL (postgres://user:pass@host:port/db)}"
for tool in psql pg_dump sha384sum; do
    command -v "$tool" >/dev/null || { echo "$tool is not installed" >&2; exit 2; }
done

migrations=crates/crawlx-storage/migrations
base_url="$CRAWLX_TEST_DATABASE_URL"
query=""
case "$base_url" in
    *\?*)
        query="?${base_url#*\?}"
        base_url="${base_url%%\?*}"
        ;;
esac
scratch="crawlx_snapshot_$$"
scratch_url="${base_url%/*}/${scratch}${query}"
export PGOPTIONS="-c client_min_messages=warning"

cleanup() {
    psql -X -q -v ON_ERROR_STOP=1 "$CRAWLX_TEST_DATABASE_URL" -c "DROP DATABASE IF EXISTS \"$scratch\"" >/dev/null 2>&1 || true
}
trap cleanup EXIT
psql -X -q -v ON_ERROR_STOP=1 "$CRAWLX_TEST_DATABASE_URL" -c "CREATE DATABASE \"$scratch\"" >/dev/null

# The bookkeeping table exactly as sqlx-postgres creates it (migrate.rs, ensure_migrations_table).
psql -X -q -v ON_ERROR_STOP=1 "$scratch_url" <<'SQL' >/dev/null
CREATE TABLE IF NOT EXISTS _sqlx_migrations (
    version BIGINT PRIMARY KEY,
    description TEXT NOT NULL,
    installed_on TIMESTAMPTZ NOT NULL DEFAULT now(),
    success BOOLEAN NOT NULL,
    checksum BYTEA NOT NULL,
    execution_time BIGINT NOT NULL
);
SQL

applied=0
last=""
for file in "$migrations"/*.sql; do
    name="$(basename "$file" .sql)"
    version="${name%%_*}"
    if [ -n "$through" ] && [ "$((10#$version))" -gt "$((10#$through))" ]; then
        continue
    fi
    description="${name#*_}"
    description="${description//_/ }"
    checksum="$(sha384sum "$file" | cut -d' ' -f1)"
    # sqlx runs the script and the bookkeeping row in one transaction (sqlx issue 1966).
    psql -X -q -1 -v ON_ERROR_STOP=1 "$scratch_url" \
        -f "$file" \
        -c "INSERT INTO _sqlx_migrations (version, description, success, checksum, execution_time) VALUES ($((10#$version)), '$description', true, '\\x$checksum', 0)" \
        >/dev/null
    applied=$((applied + 1))
    last="$version"
done
[ "$applied" -gt 0 ] || { echo "no migration <= ${through:-latest} in $migrations" >&2; exit 1; }

tmp="$(mktemp)"
{
    echo "-- crawlx schema snapshot through migration ${last} (${applied} migrations)."
    echo "-- Generated by ci/schema-snapshot.sh (pg_dump of the CI postgres major); do not edit."
    echo "-- Schema-relative: loads into the current search_path. The _sqlx_migrations rows let"
    echo "-- the embedded migrator skip these."
    # Drop pg_dump's own comments, session SETs (transaction_timeout is PG17+ only), the
    # search_path reset, CREATE SCHEMA, psql meta commands (\restrict in recent pg_dump) and
    # the schema qualifier.
    pg_dump --schema-only --no-owner --no-privileges --no-comments --schema=public "$scratch_url" \
        | grep -v -E '^(--|SET |SELECT pg_catalog\.set_config|CREATE SCHEMA |\\)' \
        | sed -E 's/\bpublic\.//g' \
        | cat -s
    echo "-- Applied migrations (version, description, checksum = SHA-384 of the file, as sqlx::migrate! computes it)."
    psql -X -q -A -t -v ON_ERROR_STOP=1 "$scratch_url" -c \
        "SELECT 'INSERT INTO _sqlx_migrations (version, description, success, checksum, execution_time) VALUES (' || version || ', ' || quote_literal(description) || ', true, ''\\x' || encode(checksum, 'hex') || ''', 0);' FROM _sqlx_migrations ORDER BY version"
} >"$tmp"
mkdir -p "$(dirname "$out")"
mv "$tmp" "$out"
echo "wrote $out (migrations 0001..${last})"
