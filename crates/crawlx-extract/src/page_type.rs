//! Deterministic page-type classification. No model, no
//! network: structural signals only, evaluated in a fixed order so the same
//! document always yields the same [`PageType`].
//!
//! Order of precedence: captcha markers, password form (login), error
//! status or error title, parked-domain phrases, search form with results,
//! repeated card structure (listing), long text (article), any other
//! data-entry form (form), otherwise unknown.

use std::collections::BTreeMap;

use scraper::{ElementRef, Html};

pub use crawlx_core::config::PageType;

use crate::dom::walk;
use crate::forms::StaticForm;

/// Signals of one page.
#[derive(Debug, Clone, Copy)]
pub struct PageInput<'a> {
    /// Parsed document (structural signals: captcha widgets, repeated cards, article markup).
    pub doc: &'a Html,
    /// Document title.
    pub title: Option<&'a str>,
    /// Plain text of the page (or its main content).
    pub text: &'a str,
    /// Static forms of the page.
    pub forms: &'a [StaticForm],
    /// HTTP status.
    pub status: u16,
    /// Response headers (`cf-mitigated: challenge` marks a challenge page).
    pub headers: &'a [(String, String)],
}

/// Minimum words for an article.
pub const ARTICLE_MIN_WORDS: usize = 300;
/// Maximum words for a page to count as an error/parked page on title/phrase alone.
pub const SHORT_PAGE_MAX_WORDS: usize = 200;
/// Sibling cards with the same tag and class that make a listing.
pub const LISTING_MIN_CARDS: usize = 5;

const CAPTCHA_CLASSES: &[&str] = &[
    "g-recaptcha",
    "h-captcha",
    "cf-turnstile",
    "cf-challenge",
    "captcha",
];
const CAPTCHA_SCRIPTS: &[&str] = &[
    "recaptcha/api.js",
    "recaptcha/enterprise.js",
    "hcaptcha.com/1/api.js",
    "challenges.cloudflare.com/turnstile",
    "/cdn-cgi/challenge-platform/",
];
const CAPTCHA_PHRASES: &[&str] = &[
    "verify you are human",
    "verify that you are not a robot",
    "checking your browser before accessing",
    "enable javascript and cookies to continue",
    "complete the security check",
];
const CAPTCHA_TITLES: &[&str] = &[
    "just a moment",
    "attention required",
    "access denied | cloudflare",
];
const ERROR_TITLES: &[&str] = &[
    "404",
    "403",
    "500",
    "502",
    "503",
    "not found",
    "page not found",
    "forbidden",
    "internal server error",
    "service unavailable",
    "bad gateway",
    "something went wrong",
    "an error occurred",
    "error",
    "oops",
];
const ERROR_PHRASES: &[&str] = &[
    "page not found",
    "the page you requested could not be found",
    "the requested url was not found",
    "this page does not exist",
    "internal server error",
    "service unavailable",
    "an unexpected error",
];
const PARKED_PHRASES: &[&str] = &[
    "this domain is for sale",
    "buy this domain",
    "domain is parked",
    "this domain may be for sale",
    "parked free",
    "sedoparking",
    "parkingcrew",
    "hugedomains",
    "domain name is for sale",
    "the domain owner has not yet put up a website",
    "website coming soon",
    "this webpage was generated by the domain owner",
];
const SEARCH_NAMES: &[&str] = &[
    "q",
    "query",
    "s",
    "search",
    "keyword",
    "keywords",
    "term",
    "searchterm",
];

fn contains_any(hay: &str, needles: &[&str]) -> bool {
    needles.iter().any(|n| hay.contains(n))
}

fn captcha_markup(doc: &Html) -> bool {
    let mut found = false;
    walk(doc.tree.root(), |el| {
        if found {
            return false;
        }
        let v = el.value();
        if let Some(cls) = v.attr("class") {
            let cls = cls.to_ascii_lowercase();
            if cls.split_whitespace().any(|c| CAPTCHA_CLASSES.contains(&c)) {
                found = true;
            }
        }
        if let Some(id) = v.attr("id") {
            if CAPTCHA_CLASSES.contains(&id.to_ascii_lowercase().as_str()) {
                found = true;
            }
        }
        if v.name() == "script" || v.name() == "iframe" {
            if let Some(src) = v.attr("src") {
                if contains_any(&src.to_ascii_lowercase(), CAPTCHA_SCRIPTS) {
                    found = true;
                }
            }
        }
        !found
    });
    found
}

fn is_search_form(f: &StaticForm) -> bool {
    f.inputs.iter().any(|i| {
        i.kind == "search"
            || (i.kind == "text" && SEARCH_NAMES.contains(&i.name.to_ascii_lowercase().as_str()))
    })
}

fn has_password(f: &StaticForm) -> bool {
    f.inputs.iter().any(|i| i.kind == "password")
}

fn visible_inputs(f: &StaticForm) -> usize {
    f.inputs
        .iter()
        .filter(|i| {
            !matches!(
                i.kind.as_str(),
                "hidden" | "submit" | "button" | "image" | "reset"
            )
        })
        .count()
}

fn has_link(el: ElementRef<'_>) -> bool {
    let mut found = false;
    walk(*el, |c| {
        if c.value().name() == "a" && c.value().attr("href").is_some() {
            found = true;
        }
        !found
    });
    found
}

/// Repeated card structure: some element has at least [`LISTING_MIN_CARDS`]
/// element children sharing tag and class, most of them carrying a link.
fn repeated_cards(doc: &Html) -> bool {
    let mut found = false;
    walk(doc.tree.root(), |el| {
        if found {
            return false;
        }
        let mut groups: BTreeMap<(String, String), (usize, usize)> = BTreeMap::new();
        for child in el.children().filter_map(ElementRef::wrap) {
            let v = child.value();
            if matches!(v.name(), "script" | "style" | "br" | "option") {
                continue;
            }
            let key = (
                v.name().to_owned(),
                v.attr("class").unwrap_or("").trim().to_owned(),
            );
            let slot = groups.entry(key).or_insert((0, 0));
            slot.0 += 1;
            if has_link(child) {
                slot.1 += 1;
            }
        }
        if groups
            .values()
            .any(|&(n, linked)| n >= LISTING_MIN_CARDS && linked.saturating_mul(5) >= n.saturating_mul(4))
        {
            found = true;
        }
        !found
    });
    found
}

fn article_markup(doc: &Html) -> bool {
    let mut paragraphs = 0usize;
    let mut article = false;
    walk(doc.tree.root(), |el| {
        match el.value().name() {
            "article" => article = true,
            "p" => paragraphs += 1,
            _ => {}
        }
        true
    });
    article || paragraphs >= 3
}

/// Classify a page. Pure and deterministic.
#[must_use]
pub fn classify(input: &PageInput<'_>) -> PageType {
    let title = input
        .title
        .map(|t| t.trim().to_ascii_lowercase())
        .unwrap_or_default();
    let text = input.text.to_ascii_lowercase();
    let words = input.text.split_whitespace().count();

    let challenge_header = input
        .headers
        .iter()
        .any(|(k, v)| k.eq_ignore_ascii_case("cf-mitigated") && v.eq_ignore_ascii_case("challenge"));
    if challenge_header
        || contains_any(&title, CAPTCHA_TITLES)
        || contains_any(&text, CAPTCHA_PHRASES)
        || captcha_markup(input.doc)
    {
        return PageType::Captcha;
    }
    if input.forms.iter().any(has_password) {
        return PageType::Login;
    }
    if input.status >= 400 {
        return PageType::Error;
    }
    if words <= SHORT_PAGE_MAX_WORDS
        && (contains_any(&title, ERROR_TITLES) || contains_any(&text, ERROR_PHRASES))
    {
        return PageType::Error;
    }
    if contains_any(&text, PARKED_PHRASES)
        || (words <= SHORT_PAGE_MAX_WORDS && contains_any(&title, PARKED_PHRASES))
    {
        return PageType::Parked;
    }
    let search_form = input.forms.iter().any(is_search_form);
    let cards = repeated_cards(input.doc);
    if search_form && (text.contains("result") || cards) {
        return PageType::Search;
    }
    if cards {
        return PageType::Listing;
    }
    if words >= ARTICLE_MIN_WORDS && article_markup(input.doc) {
        return PageType::Article;
    }
    if input
        .forms
        .iter()
        .any(|f| !is_search_form(f) && visible_inputs(f) >= 2)
    {
        return PageType::Form;
    }
    PageType::Unknown
}
