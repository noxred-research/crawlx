-- crawlx-storage SQLite baseline at schema level 46.
--
-- One transactional file: the final PostgreSQL schema after migrations 0001..0046 (there is no
-- 0021), hand-translated. Later SQLite migrations continue at 0047 in lock-step with the
-- PostgreSQL numbering. Every table carries a `-- from:` line naming the PostgreSQL migrations
-- that define it.
--
-- Mapping
--   uuid                 BLOB, the 16 raw bytes (byte order = UUIDv7 time order)
--   timestamptz          INTEGER, microseconds since the Unix epoch (UTC)
--   -infinity / +infinity  -62135596800000000 (0001-01-01) / 253402300799999999 (9999-12-31 23:59:59.999999);
--                        i64 extremes are avoided because +/- on them overflows to REAL
--   now()/clock_timestamp()  CAST(unixepoch('subsec') * 1000000 AS INTEGER), millisecond resolution
--   enum types           TEXT with a CHECK (col IN (...)) label list; labels equal `as_str()`
--   jsonb                TEXT with CHECK (json_valid(col)); NULL passes the check
--   text[] / bytea[]     TEXT holding a JSON array (bytea elements as lowercase hex strings)
--   boolean              INTEGER with CHECK (col IN (0, 1))
--   bigint/int/smallint  INTEGER; real/double precision  REAL; bytea  BLOB; octet_length  length(blob)
--   interval             microsecond integer arithmetic
--   regex CHECKs         length() plus GLOB character classes
--   identity primary key INTEGER PRIMARY KEY AUTOINCREMENT (never reuses a value)
--   other sequences and non-key identity columns draw from `crawlx_sequences`
--                        (UPDATE crawlx_sequences SET v = v + 1 WHERE name = ? RETURNING v, inside
--                        the write transaction); the value is bound by the repository
-- Every table is STRICT, so a TEXT value can never land in a BLOB (uuid) column or the reverse.
-- Applying this file needs PRAGMA foreign_keys = ON on the connection (a no-op inside a
-- transaction), as the storage backend sets for every connection.
--
-- Not carried over, and who owns the replacement
--   * Row-level security, policies, roles, SECURITY DEFINER functions: tenant isolation is the
--     application predicate behind the `TENANT_TABLES` registry in crawlx-storage.
--   * Tenant assignment on url_frontier (frontier_assign_tenant): the repository binds tenant_id;
--     the composite foreign key (tenant_id, run_id) rejects a mismatch.
--   * Confidentiality rewriting for zero-retention runs (the enforce_zdr_* triggers and their
--     helper functions): the Rust projection applied before every write. No trigger rewrites a
--     row here, because a SQLite trigger cannot assign to NEW. Reject-only content validators for
--     those tables are added with the projection. The dataset delivery validators below are
--     carried because the PostgreSQL versions already only reject.
--   * Side-effect triggers (secret expiry on run status change, retained profile revocation,
--     terminal checkpoint expiry, checkpoint artifact bounding, archive dependent erasure): the
--     repositories that own those transitions perform the same writes in the same transaction.
--   * Archive and page capture expiry (assigned from the source run by PostgreSQL): the repository
--     writes it; the validator triggers below reject a mismatch.
--   * pages.host_key (generated by a regular expression in PostgreSQL): a plain column written by
--     the repository from the canonical URL.
--   * traffic_events range partitions and traffic_events_default: one plain table.
--   * Worker eligibility SQL functions, crawlx_authenticate_key, crawlx_audit_head and the safety
--     auditor view, functions and roles: evaluated in Rust, `audit_chain_head`, or refused.
--   * lease_fence_seq and run_bootstrap_producer_fence: rows of `crawlx_sequences`.
--   * Advisory and row locks: BEGIN IMMEDIATE already holds the single database write lock, so
--     no lock table exists.
--
-- Validator triggers RAISE(ABORT, ...) with the PostgreSQL message text where it is fixed. A
-- SQLite RAISE message is a literal, so messages that embed ids in PostgreSQL omit them here.
-- The status machine message `illegal actions.status transition A -> B` is parsed by the
-- storage error mapper and is exact.

