-- from: 0041 (bootstrap identity, progress and fence never regress)
CREATE TRIGGER preserve_bootstrap_progress BEFORE UPDATE ON run_bootstrap_producers
FOR EACH ROW
BEGIN
  SELECT CASE
    WHEN NEW.producer_id IS NOT OLD.producer_id
         OR NEW.tenant_id IS NOT OLD.tenant_id
         OR NEW.run_id IS NOT OLD.run_id
         OR NEW.progress < OLD.progress
         OR NEW.fence < OLD.fence
      THEN RAISE(ABORT, 'bootstrap identity, progress and fence cannot regress')
    WHEN OLD.state = 'completed'
         AND (NEW.owner IS NOT OLD.owner OR NEW.fence IS NOT OLD.fence OR NEW.state IS NOT OLD.state
              OR NEW.leased_at IS NOT OLD.leased_at OR NEW.expires_at IS NOT OLD.expires_at
              OR NEW.progress IS NOT OLD.progress OR NEW.completed_at IS NOT OLD.completed_at)
      THEN RAISE(ABORT, 'bootstrap completion is permanent until run purge')
    WHEN (NEW.owner IS NOT OLD.owner OR (NEW.state = 'running' AND OLD.state <> 'running'))
         AND NEW.fence <= OLD.fence
      THEN RAISE(ABORT, 'bootstrap acquisition requires a newer fence')
  END;
END;

